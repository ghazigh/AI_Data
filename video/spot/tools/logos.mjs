// Turns the Simple Icons SVGs in assets/logos into src/film/logos.js (one path per mark),
// so the film inlines them as <symbol>s and never touches the network.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'assets/logos');
const out = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(resolve(dir, f), 'utf8');
  const title = (svg.match(/<title>([^<]+)<\/title>/) || [])[1] || f;
  const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]).join(' ');
  out[f.replace('.svg', '')] = { title, d };
}
writeFileSync(resolve(root, 'src/film/logos.js'), '// Generated by tools/logos.mjs from assets/logos (Simple Icons, CC0). Do not edit.\nexport const LOGOS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(Object.keys(out).length, 'logos');
